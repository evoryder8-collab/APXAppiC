#!/usr/bin/env python3
"""Traces the Watch body silhouette into a SwiftUI shape for the watch-face complications.

The complication extension has no asset catalog, and a vector outline stays sharp at every
complication size. Run from ios/APEXNative:  python3 Tools/generate-watch-figure-shape.py
"""
import cv2
import numpy as np

SOURCE = "APEXWatch/WatchAssets.xcassets/WatchHydrationSilhouette.imageset/WatchHydrationSilhouette.png"
TARGET = "APEXWatchWidgets/WaterFigureShape.swift"

alpha = cv2.imread(SOURCE, cv2.IMREAD_UNCHANGED)[:, :, 3]
mask = (cv2.GaussianBlur(alpha, (0, 0), 2.0) > 127).astype(np.uint8)
ys, xs = np.nonzero(mask)
left, top, height = xs.min(), ys.min(), ys.max() - ys.min()
contours, _ = cv2.findContours(mask, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
rings = []
for contour in contours:
    if cv2.contourArea(contour) < 40:
        continue
    simple = cv2.approxPolyDP(contour, 0.9, True)[:, 0, :]
    # Everything is in units of the figure's height, so the shape scales from one number.
    rings.append([((x - left) / height, (y - top) / height) for x, y in simple])
width = (xs.max() - left) / height
assert rings and 0.3 < width < 0.5, (len(rings), width)

lines = [
    "// Generated by Tools/generate-watch-figure-shape.py from WatchHydrationSilhouette.png. Do not edit.",
    "import SwiftUI",
    "",
    "/// The app's body silhouette as a vector outline, head at the top, in units of its own height.",
    "struct WaterFigureShape: Shape {",
    f"    static let aspectRatio: CGFloat = {width:.4f}",
    "",
    "    func path(in rect: CGRect) -> Path {",
    "        let scale = min(rect.height, rect.width / Self.aspectRatio)",
    "        let origin = CGPoint(x: rect.midX - Self.aspectRatio * scale / 2, y: rect.midY - scale / 2)",
    "        var path = Path()",
    "        for ring in Self.rings {",
    "            path.addLines(ring.map { CGPoint(x: origin.x + $0.x * scale, y: origin.y + $0.y * scale) })",
    "            path.closeSubpath()",
    "        }",
    "        return path",
    "    }",
    "",
    "    private static let rings: [[CGPoint]] = [",
]
for ring in rings:
    lines.append("        [")
    for start in range(0, len(ring), 6):
        chunk = ", ".join(f"CGPoint(x: {x:.4f}, y: {y:.4f})" for x, y in ring[start:start + 6])
        lines.append(f"            {chunk},")
    lines.append("        ],")
lines += ["    ]", "}", ""]
open(TARGET, "w").write("\n".join(lines))
print(f"{len(rings)} rings, {sum(len(r) for r in rings)} points, aspect {width:.4f}")
